CREATE OR REPLACE PROCEDURE "PR_SOLICITAR_DEVOLUCION" (
  p_id_factura IN  NUMBER,
  p_id_cliente IN  NUMBER,
  p_monto      OUT NUMBER,
  p_id_pago    OUT VARCHAR2,
  p_metodo     OUT VARCHAR2
) AS
  c_dias_minimos CONSTANT NUMBER := 5;
  v_ahora        DATE := CAST(SYSTIMESTAMP AT TIME ZONE 'America/Costa_Rica' AS DATE);
  v_activos      NUMBER;
  v_funcion      DATE;
BEGIN
  -- Factura del cliente, bloqueada hasta el COMMIT o el ROLLBACK
  BEGIN
    SELECT f."ID_INTENCION_PAGO", m."NOMBRE_METODO"
      INTO p_id_pago, p_metodo
      FROM "FACTURAS_FINALES" f
      JOIN "METODOS_PAGO" m ON m."ID_METODO" = f."ID_METODO"
     WHERE f."ID_FACTURA" = p_id_factura
       AND f."ID_CLIENTE" = p_id_cliente
       FOR UPDATE OF f."ID_FACTURA";
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20020, 'La compra no existe');
  END;

  -- Boletos activos de la factura: cuántos, cuánto suman y cuándo es la función
  SELECT COUNT(*), NVL(SUM(df."MONTO"), 0), MIN(p."FECHA")
    INTO v_activos, p_monto, v_funcion
    FROM "DETALLES_FACTURA" df
    JOIN "PROYECCIONES" p ON p."ID_PROYECCION" = df."ID_PROYECCION"
   WHERE df."ID_FACTURA" = p_id_factura
     AND df."TIPO_FACTURA" = 'BOLETO'
     AND df."ESTADO_DETALLE" = 'ACTIVO';

  IF v_activos = 0 THEN
    RAISE_APPLICATION_ERROR(-20021, 'Esta compra ya fue cancelada');
  END IF;

  IF v_funcion - v_ahora < c_dias_minimos THEN
    RAISE_APPLICATION_ERROR(-20022, 'Solo puedes cancelar tu compra hasta 5 días antes de la función');
  END IF;

  IF p_id_pago IS NULL THEN
    RAISE_APPLICATION_ERROR(-20023, 'La compra no tiene un pago registrado');
  END IF;

  -- Solo se toca ESTADO_DETALLE (ver TR_DETALLES_FACTURA_INMUTABLE)
  UPDATE "DETALLES_FACTURA"
     SET "ESTADO_DETALLE" = 'DEVUELTO'
   WHERE "ID_FACTURA" = p_id_factura
     AND "TIPO_FACTURA" = 'BOLETO'
     AND "ESTADO_DETALLE" = 'ACTIVO';

  BEGIN
    INSERT INTO "DEVOLUCIONES" ("ID_FACTURA", "FECHA", "MONTO")
    VALUES (p_id_factura, v_ahora, p_monto);
  EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
      RAISE_APPLICATION_ERROR(-20021, 'Esta compra ya fue cancelada');
  END;
END;
/


CREATE OR REPLACE PROCEDURE "PR_CONFIRMAR_DEVOLUCION" (
  p_id_factura   IN NUMBER,
  p_id_reembolso IN VARCHAR2
) AS
BEGIN
  UPDATE "DEVOLUCIONES"
     SET "ID_REEMBOLSO" = p_id_reembolso
   WHERE "ID_FACTURA" = p_id_factura;

  IF SQL%ROWCOUNT = 0 THEN
    RAISE_APPLICATION_ERROR(-20024, 'No hay una devolución que confirmar para esta compra');
  END IF;
END;
