-- Parte D: triggers y procedimientos almacenados
--
-- Códigos de error propios (RAISE_APPLICATION_ERROR), que el servidor traduce a HTTP:
--   -20020  La compra no existe o no es del cliente                    -> 404
--   -20021  La compra ya fue cancelada                                  -> 409
--   -20022  Faltan menos de 5 días para la función                     -> 409
--   -20023  La compra no tiene un pago registrado (no se puede reembolsar) -> 500
--   -20024  No hay devolución que confirmar para esa factura           -> 500
--   -20030  Se intentó modificar un dato de un boleto vendido           (trigger)
--   -20031  Cambio de estado no permitido (solo ACTIVO -> DEVUELTO)     (trigger)

CREATE OR REPLACE TRIGGER "TR_DETALLES_FACTURA_INMUTABLE"
BEFORE UPDATE ON "DETALLES_FACTURA"
FOR EACH ROW
BEGIN
  IF UPDATING('ID_DETALLE_FACTURA') OR UPDATING('ID_FACTURA') OR UPDATING('ID_ASIENTO')
     OR UPDATING('ID_PROYECCION') OR UPDATING('TIPO_FACTURA') OR UPDATING('CANTIDAD')
     OR UPDATING('MONTO') OR UPDATING('DESCUENTO') OR UPDATING('ID_CANTIDAD_PRODUCTO')
     OR UPDATING('ID_TIPO_BOLETO') OR UPDATING('ID_DESCUENTO') THEN
    RAISE_APPLICATION_ERROR(-20030, 'Los datos de una venta no se pueden modificar');
  END IF;

  IF UPDATING('ESTADO_DETALLE')
     AND NOT (:OLD."ESTADO_DETALLE" = 'ACTIVO' AND :NEW."ESTADO_DETALLE" = 'DEVUELTO') THEN
    RAISE_APPLICATION_ERROR(-20031, 'Solo se puede pasar un boleto de ACTIVO a DEVUELTO');
  END IF;
END;
