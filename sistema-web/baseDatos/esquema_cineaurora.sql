BEFORE UPDATE OF ID_FORMATO
ON SALAS
FOR EACH ROW
BEGIN
    IF :OLD.ID_FORMATO <> :NEW.ID_FORMATO THEN
        RAISE_APPLICATION_ERROR(
            -20002,
            'El formato de una sala no puede modificarse despues de su creacion.'
        );
    END IF;
END;
